import puppeteer from 'puppeteer'
const browser = await puppeteer.launch({ headless: true, args: ['--no-sandbox'], defaultViewport: { width: 1300, height: 880 } })
const page = await browser.newPage()
await page.goto('http://localhost:3000/2026-05-31-weingut-barbazza/index.html', { waitUntil: 'domcontentloaded', timeout: 40000 }).catch(() => {})
await new Promise(r => setTimeout(r, 1800))
const en = await page.evaluate(() => { const el = document.querySelector('.hero h1 [data-i18n="hero.h1"]'); return el ? el.innerText : '(missing)' })
console.log('  EN hero.h1 (\\n = line break):', JSON.stringify(en))
await page.screenshot({ path: '.claude/hero-en.png' })
await page.evaluate(() => { const b = [...document.querySelectorAll('.langsw button[data-lang]')].find(x => x.getAttribute('data-lang') === 'it'); b && b.click() })
await new Promise(r => setTimeout(r, 500))
const it = await page.evaluate(() => document.querySelector('.hero h1 [data-i18n="hero.h1"]')?.innerText)
console.log('  IT hero.h1:', JSON.stringify(it))
await page.screenshot({ path: '.claude/hero-it.png' })
await browser.close()
